"""Cross-implementation tests: the Python codec must agree byte-for-byte with the
TypeScript reference (tests/vectors.json was generated by it) and with the
published spec's own worked examples."""
import json
from pathlib import Path

import pytest

from singularis_rf.codec import (
    CodecError, FrameAssembler, Spec, crc16, decode_frames, decode_payload, encode_message, encode_payload,
    escape_value, normalize_identifier, parse_frame, unescape_value, looks_like_frame,
)

HERE = Path(__file__).parent
SPEC = Spec.load(HERE.parent / "spec" / "singularis-compact.json")
VECTORS = json.loads((HERE / "vectors.json").read_text(encoding="utf-8"))


def test_spec_loaded_from_published_json():
    assert SPEC.protocol == "SP1"
    assert set(SPEC.blocks) == set("RATXPLESOF")
    assert SPEC.blocks["P"] == "GR::PONG"


def test_crc_check_value():
    assert crc16("123456789") == "29B1"


def test_escaping_round_trip():
    s = "a b_c;d=e|f#g~h>i:j%k+l Φ"
    e = escape_value(s)
    assert "a+b_c" in e and "k%2Bl" in e
    assert not any(ch in e for ch in " ;=|#~>:")
    assert unescape_value(e) == s


def test_identifiers():
    assert normalize_identifier("kannaka-prime") == "KANNAKA-PRIME"
    assert normalize_identifier("smoke swarm agent") == "SMOKE-SWARM-AGEN"
    assert normalize_identifier("") == "*"
    with pytest.raises(CodecError):
        normalize_identifier("---")


@pytest.mark.parametrize("i", range(len(VECTORS)))
def test_vector_decodes_to_reference_blocks(i):
    v = VECTORS[i]
    msg = decode_frames(SPEC, v["frames"])
    assert msg.blocks == v["blocks"]
    assert msg.from_ == normalize_identifier(v["opts"]["from"])
    assert msg.to == normalize_identifier(v["opts"].get("to") or "*")
    assert msg.message_id == v["opts"]["messageId"].upper()
    assert msg.experiment_id == v["opts"].get("experimentId")


@pytest.mark.parametrize("i", range(len(VECTORS)))
def test_vector_reencodes_identically(i):
    """Encoder parity: same blocks + options → the exact same frames the TypeScript encoder produced."""
    v = VECTORS[i]
    o = v["opts"]
    assert encode_payload(SPEC, v["blocks"], o.get("experimentId")) == v["payload"]
    frames = encode_message(SPEC, v["blocks"], from_=o["from"], to=o.get("to"), message_id=o["messageId"],
                            experiment_id=o.get("experimentId"), frame_length=o.get("frameLength", 67))
    assert frames == v["frames"]


def test_vectors_respect_frame_length():
    for v in VECTORS:
        limit = v["opts"].get("frameLength", 67)
        assert all(len(f) <= limit for f in v["frames"])
        assert all(parse_frame(f).crc_ok for f in v["frames"])


def test_spec_examples_decode():
    for ex in SPEC.raw["examples"]:
        msg = decode_frames(SPEC, ex["frames"])
        assert msg.blocks == ex["blocks"]


def test_tamper_gap_and_mix_are_rejected():
    v = next(v for v in VECTORS if len(v["frames"]) >= 3)
    frames = v["frames"]
    bad = list(frames)
    bad[1] = bad[1][:-1] + ("0" if bad[1][-1] != "0" else "1")
    assert not parse_frame(bad[1]).crc_ok
    with pytest.raises(CodecError, match="CRC failure"):
        decode_frames(SPEC, bad)
    with pytest.raises(CodecError, match="Missing frame 1"):
        decode_frames(SPEC, frames[1:])
    other = next(w for w in VECTORS if w["opts"]["messageId"] != v["opts"]["messageId"])
    with pytest.raises(CodecError, match="different messages"):
        decode_frames(SPEC, frames + other["frames"])


def test_assembler_out_of_order_duplicates_and_noise():
    v = next(v for v in VECTORS if len(v["frames"]) >= 3)
    asm = FrameAssembler(SPEC)
    order = [v["frames"][-1], v["frames"][0], v["frames"][0], "CQ CQ DE AE0RM", *v["frames"][1:-1]]
    result = None
    for line in order:
        r = asm.feed(line, now=100.0)
        if r:
            result = r
    assert result is not None
    assert result[0].blocks == v["blocks"]
    assert asm.pending_count == 0


def test_assembler_expires_stale_partials():
    v = next(v for v in VECTORS if len(v["frames"]) >= 2)
    asm = FrameAssembler(SPEC, ttl_s=10)
    asm.feed(v["frames"][0], now=0.0)
    assert asm.pending_count == 1
    other = next(w for w in VECTORS if len(w["frames"]) == 1)
    asm.feed(other["frames"][0], now=1000.0)
    assert asm.pending_count == 0


def test_looks_like_frame_filters_ordinary_traffic():
    assert looks_like_frame(VECTORS[0]["frames"][0])
    assert not looks_like_frame("AE0RM>APRS:>Testing 1 2 3")
    assert not looks_like_frame("CQ CQ CQ DE W1AW")


def test_payload_meta_and_unknown_tokens():
    p = encode_payload(SPEC, [{"type": "GR::LISTEN", "detect": ["a"], "reject": ["b"]}], "e 1", "s")
    assert p.startswith("@x=e+1 @s=s L ")
    blocks, exp, sess = decode_payload(SPEC, p)
    assert (exp, sess) == ("e 1", "s") and blocks[0]["type"] == "GR::LISTEN"
    with pytest.raises(CodecError, match="Unknown meta token"):
        decode_payload(SPEC, "@q=1 L d=a j=b")
    with pytest.raises(CodecError, match="Unknown key"):
        decode_payload(SPEC, "R i=o d=N s=R t=O zz=1")
